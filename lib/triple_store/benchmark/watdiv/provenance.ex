defmodule TripleStore.Benchmark.WatDiv.Provenance do
  @moduledoc """
  Validates official WatDiv dataset provenance before a benchmark run.

  A manifest binds the generated N-Triples file to the upstream WatDiv version,
  source archive, dataset-description model, scale factor, checksum, and exact
  statement count. The local artifact is re-hashed and re-counted on load.
  """

  alias TripleStore.Benchmark.Artifact

  @official_archive_md5 "9eac247dfdec044d7fa0141ea3ad361f"
  @official_archive_url "https://dsg.uwaterloo.ca/watdiv/watdiv_v06.tar"
  @official_model_sha256 "sha256:8a888eded6552b981857f7f0cd0c92cf04de3cf4801ec91dba9e4dd18a32bf76"

  @type t :: %{
          schema_version: pos_integer(),
          benchmark: String.t(),
          watdiv_version: String.t(),
          scale_factor: pos_integer(),
          generator: String.t(),
          source_archive_url: String.t(),
          source_archive_md5: String.t(),
          model_sha256: String.t(),
          dataset_sha256: String.t(),
          triple_count: pos_integer(),
          dataset_path: Path.t(),
          manifest_path: Path.t()
        }

  @doc "Loads a JSON manifest and verifies its referenced local dataset."
  @spec load_dataset_manifest(Path.t(), Path.t()) :: {:ok, t()} | {:error, term()}
  def load_dataset_manifest(manifest_path, dataset_path)
      when is_binary(manifest_path) and is_binary(dataset_path) do
    with {:ok, json} <- File.read(manifest_path),
         {:ok, manifest} when is_map(manifest) <- Jason.decode(json),
         :ok <- validate_manifest(manifest),
         :ok <- Artifact.verify_checksum(dataset_path, manifest["dataset_sha256"]),
         {:ok, count} <- Artifact.statement_count(dataset_path),
         :ok <- verify_count(manifest["triple_count"], count) do
      {:ok,
       %{
         schema_version: manifest["schema_version"],
         benchmark: manifest["benchmark"],
         watdiv_version: manifest["watdiv_version"],
         scale_factor: manifest["scale_factor"],
         generator: manifest["generator"],
         source_archive_url: manifest["source_archive_url"],
         source_archive_md5: manifest["source_archive_md5"],
         model_sha256: manifest["model_sha256"],
         dataset_sha256: manifest["dataset_sha256"],
         triple_count: count,
         dataset_path: Path.expand(dataset_path),
         manifest_path: Path.expand(manifest_path)
       }}
    else
      {:ok, _other} -> {:error, :invalid_manifest_json}
      {:error, _reason} = error -> error
    end
  end

  @doc "Writes a manifest for a dataset generated by the pinned official tool."
  @spec write_dataset_manifest(Path.t(), Path.t(), Path.t(), pos_integer()) ::
          {:ok, map()} | {:error, term()}
  def write_dataset_manifest(dataset_path, model_path, output_path, scale_factor)
      when is_binary(dataset_path) and is_binary(model_path) and is_binary(output_path) and
             is_integer(scale_factor) and scale_factor > 0 do
    with {:ok, dataset_sha256} <- Artifact.checksum(dataset_path),
         :ok <- Artifact.verify_checksum(model_path, @official_model_sha256),
         {:ok, triple_count} <- Artifact.statement_count(dataset_path),
         :ok <- File.mkdir_p(Path.dirname(output_path)) do
      manifest = %{
        schema_version: 1,
        benchmark: "watdiv",
        watdiv_version: "0.6",
        scale_factor: scale_factor,
        generator: "official-watdiv-v0.6",
        source_archive_url: @official_archive_url,
        source_archive_md5: @official_archive_md5,
        model_sha256: @official_model_sha256,
        dataset_sha256: dataset_sha256,
        triple_count: triple_count
      }

      case File.write(output_path, Jason.encode!(manifest, pretty: true)) do
        :ok -> {:ok, manifest}
        {:error, _reason} = error -> error
      end
    end
  end

  @doc "Returns the pinned upstream source metadata used by preparation scripts."
  @spec upstream() :: map()
  def upstream do
    %{
      version: "0.6",
      archive_url: @official_archive_url,
      archive_md5: @official_archive_md5,
      model_sha256: @official_model_sha256
    }
  end

  defp validate_manifest(manifest) do
    errors =
      []
      |> require_equal(manifest, "schema_version", 1, "schema_version must be 1")
      |> require_equal(manifest, "benchmark", "watdiv", "benchmark must be watdiv")
      |> require_equal(manifest, "watdiv_version", "0.6", "watdiv_version must be 0.6")
      |> require_positive_integer(manifest, "scale_factor")
      |> require_official_generator(manifest)
      |> require_equal(
        manifest,
        "source_archive_url",
        @official_archive_url,
        "source_archive_url must identify the official WatDiv v0.6 archive"
      )
      |> require_equal(
        manifest,
        "source_archive_md5",
        @official_archive_md5,
        "source_archive_md5 must match the published WatDiv v0.6 digest"
      )
      |> require_equal(
        manifest,
        "model_sha256",
        @official_model_sha256,
        "model_sha256 must match the model in the official WatDiv v0.6 archive"
      )
      |> require_sha256(manifest, "dataset_sha256")
      |> require_positive_integer(manifest, "triple_count")

    if errors == [], do: :ok, else: {:error, {:invalid_manifest, Enum.reverse(errors)}}
  end

  defp require_equal(errors, manifest, key, expected, message) do
    if manifest[key] == expected, do: errors, else: [message | errors]
  end

  defp require_positive_integer(errors, manifest, key) do
    if is_integer(manifest[key]) and manifest[key] > 0,
      do: errors,
      else: ["#{key} must be a positive integer" | errors]
  end

  defp require_official_generator(errors, manifest) do
    case manifest["generator"] do
      "official-watdiv-v0.6" -> errors
      _ -> ["generator must identify the official WatDiv tool" | errors]
    end
  end

  defp require_sha256(errors, manifest, key) do
    case manifest[key] do
      "sha256:" <> digest when byte_size(digest) == 64 -> errors
      _ -> ["#{key} must be a sha256 digest" | errors]
    end
  end

  defp verify_count(expected, expected), do: :ok
  defp verify_count(expected, actual), do: {:error, {:triple_count_mismatch, expected, actual}}
end
